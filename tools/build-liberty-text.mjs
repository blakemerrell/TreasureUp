#!/usr/bin/env node
// Builds liberty/scripture.js: the chapters Title of Liberty's missions are
// read from (a mission opens once its chapter is read). Same pinned
// public-domain data as tools/verify.mjs. Add a mission's chapter to
// CHAPTERS and run:  node tools/build-liberty-text.mjs
// (tools/.scripture-cache is filled by running tools/verify.mjs once.)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const CHAPTERS = ['3 Nephi 3', '3 Nephi 4'];

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = process.env.SCRIPTURE_CACHE || path.join(ROOT, 'tools', '.scripture-cache');
const files = fs.existsSync(CACHE) ? fs.readdirSync(CACHE) : [];
const chapters = new Map();
for (const name of ['old-testament', 'new-testament', 'book-of-mormon', 'doctrine-and-covenants', 'pearl-of-great-price']) {
  const f = files.find(x => x.endsWith('-' + name + '.json'));
  if (!f) throw new Error('Run node tools/verify.mjs once first, to download the scripture data');
  const data = JSON.parse(fs.readFileSync(path.join(CACHE, f), 'utf8'));
  for (const c of data.sections || data.books.flatMap(b => b.chapters)) {
    for (const v of c.verses) {
      const key = v.reference.replace(/:\d+$/, '');
      if (!chapters.has(key)) chapters.set(key, []);
      chapters.get(key)[v.verse - 1] = v.text;
    }
  }
}
const out = {};
for (const ch of CHAPTERS) {
  if (!chapters.has(ch)) throw new Error(`"${ch}" isn't in the scripture data`);
  out[ch] = chapters.get(ch);
}
fs.writeFileSync(path.join(ROOT, 'liberty', 'scripture.js'),
  '// Generated by tools/build-liberty-text.mjs from bcbooks/scriptures-json (public domain),\n' +
  '// the same pinned data tools/verify.mjs checks quotes against. Do not edit by hand.\n' +
  'window.LIBERTY_SCRIPTURE = ' + JSON.stringify(out, null, 1) + ';\n');
console.log(`liberty/scripture.js: ${CHAPTERS.join(', ')}`);
